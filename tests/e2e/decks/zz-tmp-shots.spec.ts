import { expect, test } from '@playwright/test';
import { decklist, decks, libraryV1, openDecks, profileOf } from './helpers';

test('tmp shots', async ({ page }, info) => {
  await openDecks(page, { profile: profileOf(info) });
  await page.evaluate((text) => window.__decksHarness!.seedLibrary(text), libraryV1());
  await page.goto(`./?harness=decks&faces=placeholder&profile=${profileOf(info)}#/decks/new/import`);
  await page.getByTestId('deck-text').fill(decklist('gw-m19-60.txt'));
  await page.getByTestId('deck-check').click();
  await page.getByTestId('deck-import-go').click();
  await expect(page.getByTestId('deck-page')).toBeVisible();
  await page.getByTestId('card-search').fill('t:creature');
  await expect(page.getByTestId('result-card').first()).toBeVisible();
  await page.waitForTimeout(800);
  await page.screenshot({ path: 'artifacts/tmp/deck-page.png' });
  await page.evaluate(() => (location.hash = '#/decks'));
  await expect(page.getByTestId('deck-tile')).toHaveCount(3);
  await page.waitForTimeout(500);
  await page.locator('[data-testid="deck-tile"]').nth(1).hover();
  await page.screenshot({ path: 'artifacts/tmp/library.png' });
  await page.evaluate(() => (location.hash = '#/decks/new'));
  await decks(page, 'nextSeed', 'b2'.repeat(32));
  await page.screenshot({ path: 'artifacts/tmp/chooser.png' });
  await page.getByTestId('open-setup').click();
  await page.waitForTimeout(300);
  await page.screenshot({ path: 'artifacts/tmp/setup.png' });
  await page.getByTestId('setup-open').click();
  await expect(page.getByTestId('opening-card')).toHaveCount(15);
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'artifacts/tmp/opening.png' });
  await page.getByTestId('open-all').click();
  await expect(page.getByTestId('pool-grid')).toBeVisible();
  await page.waitForTimeout(800);
  await page.screenshot({ path: 'artifacts/tmp/pool.png' });
});
