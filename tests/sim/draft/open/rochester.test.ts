/**
 * PLAN M2-P3 acceptance on a simulated network: a Rochester draft for 2, 3 and 4 seats driven end to end by the
 * drivers (draft/rochester.ts) over LoopbackNetwork with delay, reordering and dropped messages (DESIGN "Specification:
 * card data, packs and draft formats", Rochester: snake order from the opener, the opener role moves left, `burn`
 * cards left unpicked). The sequenced log must show the design's order; every pool must hold exactly the cards its
 * drafter picked, with the identities the packs showed face up.
 */
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { verifyReveal } from '../../../../src/core/commit';
import type { SeatId } from '../../../../src/core/types';
import { draftNet, runDraft, close, type DraftSeat } from './net';
import { mulberry32 } from '../../../../src/util/prng';

beforeEach(() => {
  vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout', 'setInterval', 'clearInterval', 'Date'] });
});
afterEach(() => {
  vi.useRealTimers();
});

/** The design's snake: position i of a pack opened by `opener` (left = next higher seat index). */
function snake(seats: readonly SeatId[], opener: SeatId, i: number): SeatId {
  const s = seats.length;
  const o = seats.indexOf(opener);
  const c = i % (2 * s);
  return seats[(o + (c < s ? c : 2 * s - 1 - c)) % s]!;
}

/** A drafter who picks a random card of the pack when it is their pick (first marking it, as the HUD does). */
function randomPicker(seed: number): (s: DraftSeat) => void {
  const rand = mulberry32(seed);
  return (s) => {
    const v = s.driver.view();
    if (v.pack === null || !v.waitingOn.includes(s.seat)) return;
    const card = v.pack.cards[Math.floor(rand() * v.pack.cards.length)]!;
    s.driver.mark([card.id]);
    expect(s.driver.view().marked).toEqual([card.id]);
    expect(s.driver.pick([card.id])).toBe(true);
  };
}

describe('Rochester over the network', () => {
  for (const [seats, packs, burn] of [
    [2, 2, 0],
    [3, 1, 2],
    [4, 1, 3],
  ] as const) {
    it(`${seats} seats, ${packs} pack(s) each, burn ${burn}`, async () => {
      const t = await draftNet(seats, { format: 'rochester', packs, burn }, { seed: seats, delay: { min: 0, max: 80 }, drop: 0.05, faultyChannels: ['act', 'ctl'] });
      const ids = t.seats.map((s) => s.seat);
      // Nobody may pick out of turn: a pick by any other seat is refused (and changes nothing).
      let refused = 0;
      const bot = randomPicker(seats * 31);
      await runDraft(t, (s) => {
        const v = s.driver.view();
        if (v.pack !== null && !v.waitingOn.includes(s.seat)) {
          if (!s.driver.pick([v.pack.cards[0]!.id])) refused++;
        }
        bot(s);
      });
      expect(refused).toBeGreaterThan(0);

      const log = t.seats[0]!.peer.log();
      const opens = log.filter((a) => a.type === 'packOpen');
      const final = t.seats[0]!.peer.state.draft!;
      expect(final.done).toBe(true);
      // The opener rotates left: every player opened `packs` packs, in seat order.
      expect(opens.map((a) => a.by)).toEqual(Array.from({ length: packs * seats }, (_, k) => ids[k % seats]));
      // Picks per pack follow the snake from that pack's opener, until `burn` cards remain.
      for (const open of opens) {
        if (open.type !== 'packOpen') continue;
        const picks = log.filter((a) => a.type === 'pick' && a.packId === open.packId);
        expect(picks.map((a) => a.by)).toEqual(picks.map((_, i) => snake(ids, open.by, i)));
        expect(picks).toHaveLength(open.count - burn);
        const pack = final.packs[open.packId]!;
        expect(pack.count).toBe(burn);
        // Every pack card was generated by its opener and opens the published commitments.
        for (const c of open.cards ?? []) expect(verifyReveal(pack.commitment, c)).toBe(true);
      }
      // Every browser agrees, and every pool holds exactly its drafter's picks with their face-up identities.
      for (const s of t.seats) expect(s.peer.state).toEqual(t.seats[0]!.peer.state);
      const shown = new Map(opens.flatMap((a) => (a.type === 'packOpen' ? (a.cards ?? []) : [])).map((c) => [c.instanceId, c.ref]));
      for (const s of t.seats) {
        const mine = log.filter((a) => a.type === 'pick' && a.by === s.seat).map((a) => (a.type === 'pick' ? a.cards![0]! : ''));
        expect(final.taken![s.seat]).toEqual(mine);
        expect(s.secrets().pool).toEqual(mine.map((id) => shown.get(id)));
        // The opener kept an audit record per pack it generated.
        expect(s.secrets().draft!.generated.map((g) => g.packId)).toEqual(opens.filter((a) => a.by === s.seat).map((a) => (a.type === 'packOpen' ? a.packId : '')));
      }
      close(t);
    }, 120_000);
  }

  it('a reload mid-draft keeps the pool and goes on', async () => {
    const t = await draftNet(2, { format: 'rochester', packs: 1, burn: 0 }, { seed: 9, delay: { min: 0, max: 40 } });
    const bot = randomPicker(9);
    let reloaded = false;
    await runDraft(t, (s) => {
      if (!reloaded && s.seat === 's1' && (s.secrets().pool ?? []).length >= 3) {
        s.reload();
        reloaded = true;
      }
      bot(s);
    });
    expect(reloaded).toBe(true);
    const final = t.seats[0]!.peer.state.draft!;
    for (const s of t.seats) expect(s.secrets().pool).toHaveLength(final.taken![s.seat]!.length);
    close(t);
  }, 120_000);
});
